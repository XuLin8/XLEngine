	void TextRenderer::Init()
	{
		BuildTexture();
	}

	void TextRenderer::Shutdown()
	{
		s_Atlas = nullptr;
	}

	void TextRenderer::BuildTexture()
	{
		constexpr int cols = 5;
		constexpr int rows = 7;
		constexpr int nchars = 95;
		constexpr int stride = 1; // 1px 间距
		constexpr int atlasW = nchars * (cols + stride);
		constexpr int atlasH = rows;

		uint8_t* pixels = new uint8_t[atlasW * atlasH];
		memset(pixels, 0, atlasW * atlasH);

		for (int c = 0; c < nchars; c++)
		{
			for (int col = 0; col < cols; col++)
			{
				uint8_t bits = s_Font[c][col];
				for (int r = 0; r < rows; r++)
				{
					bool on = (bits >> r) & 0x01;
					int px = c * (cols + stride) + col;
					int py = r; // 顶行为 atlas 顶部
					pixels[py * atlasW + px] = on ? 255 : 0;
				}
			}
		}

		s_Atlas = Texture2D::Create((uint32_t)atlasW, (uint32_t)atlasH);
		s_Atlas->SetData(pixels, atlasW * atlasH);
		delete[] pixels;

		s_AtlasInvW = 1.0f / (float)atlasW;
		s_AtlasInvH = 1.0f / (float)atlasH;
		s_BaseAscii = 0x20; // font[0]=占位符，font[1]='!': glyph 0x21 -> idx 1
	}

	void TextRenderer::BeginScene(uint32_t w, uint32_t h)
	{
		Renderer2D::BeginScene(MakeOrthoCamera(w, h), glm::mat4(1.0f));
	}

	void TextRenderer::EndScene()
	{
		Renderer2D::EndScene();
	}

	float TextRenderer::MeasureWidth(const std::string& text, float scale)
	{
		constexpr int cols = 5;
		constexpr int stride = 1;
		int count = (int)text.size();
		if (count == 0)
			return 0.0f;
		// 每字符 6px（5+1），末字符省去右间距
		return (float)(cols * count + stride * (count - 1)) * scale;
	}

	void TextRenderer::DrawString(const std::string& text, float x, float y, float scale, const glm::vec4& color)
	{
		if (!s_Atlas)
			return;

		constexpr int cols = 5;
		constexpr int rows = 7;
		constexpr int stride = 1;

		float advance = (float)(cols + stride) * scale;
		float baseline = y; // 屏幕 y 向上，点阵顶行为最高点

		int i = 0;
		for (char ch : text)
		{
			int glyph = (int)(unsigned char)ch;
			float ox = x + i * advance;

			if (glyph == ' ')
			{
				// 空格：仅前进
				i++;
				continue;
			}

			if (glyph >= 0x21 && glyph <= 0x7F)
			{
				int idx = glyph - s_BaseAscii;
				int atlasX = idx * (cols + stride);
				// SubTexture UV（纹理坐标 0,0 = 左下角，需要翻转 Y）
				float u0 = atlasX * s_AtlasInvW;
				float u1 = (atlasX + cols) * s_AtlasInvW;
				float v1 = 0.0f; // 顶行 -> v 最高
				float v0 = (float)rows * s_AtlasInvH;

				// 顶点 UV 顺序：DrawQuad 用 texcoords {0,0},{1,0},{1,1},{0,1}
				// 期望顶部（屏幕 y 高处）对应字形顶行 -> uv.v 较大（上）
				// 字形顶行(row0) 位于 atlas 上 -> 映射到 v=1（顶部）
				Ref<SubTexture2D> sub = CreateRef<SubTexture2D>(s_Atlas, glm::vec2(u0, v0), glm::vec2(u1, v1));
				glm::vec2 size((float)cols * scale, (float)rows * scale);
				glm::vec2 pos(ox, baseline); // 左下角
				Renderer2D::DrawQuad(pos, size, sub, 1.0f, color);
			}
			i++;
		}
	}
